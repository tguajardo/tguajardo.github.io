/* ---------------------------
   Render function
---------------------------- */
function renderLanguage(lang) {
  const c = content[lang];

  document.getElementById('name').textContent = c.name;
  document.getElementById('headline').textContent = c.headline;

  document.getElementById('about-title').textContent = c.aboutTitle;
  document.getElementById('about-tag').textContent = c.aboutTag;
  document.getElementById('about-text').textContent = c.aboutText;
  document.getElementById('about-extra').textContent = c.aboutExtra;

  document.getElementById('skills-title').textContent = c.skillsTitle;
  document.getElementById('skills-tag').textContent = c.skillsTag;
  document.getElementById('skills-intro').textContent = c.skillsIntro;

  const techContainer = document.getElementById('skills-tech');
  const softContainer = document.getElementById('skills-soft');
  techContainer.innerHTML = '';
  softContainer.innerHTML = '';

  c.skillsTech.forEach((t) => {
    const span = document.createElement('span');
    span.className = 'pill primary';
    span.textContent = t;
    techContainer.appendChild(span);
  });

  c.skillsSoft.forEach((t) => {
    const span = document.createElement('span');
    span.className = 'pill';
    span.textContent = t;
    softContainer.appendChild(span);
  });

  document.getElementById('projects-title').textContent = c.projectsTitle;
  document.getElementById('projects-tag').textContent = c.projectsTag;
  document.getElementById('projects-intro').textContent = c.projectsIntro;

  const projContainer = document.getElementById('projects-list');
  projContainer.innerHTML = '';
  c.projects.forEach((p) => {
    const div = document.createElement('div');
    div.innerHTML = `
      <div class="item-title">${p.title}</div>
      <div class="item-sub">${p.sub}</div>
      <div class="item-desc">${p.desc}</div>
    `;
    projContainer.appendChild(div);
  });

  const expContainer = document.getElementById('experience-list');
  expContainer.innerHTML = '';
  c.experience.forEach((e) => {
    const div = document.createElement('div');
    div.innerHTML = `
      <div class="item-title">${e.title}</div>
      <div class="item-sub">${e.sub}</div>
      <div class="item-desc">${e.desc}</div>
    `;
    expContainer.appendChild(div);
  });

  document.getElementById('contact-title').textContent = c.contactTitle;
  document.getElementById('contact-tag').textContent = c.contactTag;
  document.getElementById('phone-label').textContent = c.phoneLabel;
  document.getElementById('email-label').textContent = c.emailLabel;
  document.getElementById('footer-text').textContent = c.footerText;

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

/* ---------------------------
   Language switch buttons
---------------------------- */
document.querySelectorAll('.lang-btn').forEach((btn) => {
  btn.addEventListener('click', () => {
    renderLanguage(btn.dataset.lang);
  });
});

/* Initial render */
renderLanguage('en');

/* Theme toggle */
const themeToggle = document.getElementById('theme-toggle');

themeToggle.addEventListener('click', () => {
  document.documentElement.classList.toggle('light');

  const mode = document.documentElement.classList.contains('light') ? 'light' : 'dark';

  localStorage.setItem('theme', mode);
});

/* Load saved theme */
const savedTheme = localStorage.getItem('theme');
if (savedTheme === 'light') {
  document.documentElement.classList.add('light');
}
